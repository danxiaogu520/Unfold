import { expect, test } from '@playwright/test';

test('one layer, leaf, explanation history and changed profile survive refresh', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByLabel('你想学习什么？').fill('知识路径 · M2 浏览器验收');
  await page.getByLabel('你希望用它做什么？').fill('理解概念并练习实际应用。');
  await page.getByRole('button', { name: '开始探索' }).click();
  await expect(page.getByRole('checkbox', { name: '暂不确定', exact: true })).toBeVisible();
  await page.getByRole('checkbox', { name: '暂不确定', exact: true }).check();
  await page.getByRole('button', { name: '整理学习设定' }).click();
  // The saved profile atomically registers the first outline without another click.
  await expect(page.getByRole('heading', { name: '下一层知识' })).toBeVisible();
  await page.getByRole('button', { name: /知识节点.*应用与边界/ }).click();
  await expect(page.getByText('当前目标的叶子').first()).toBeVisible();
  await expect(page.getByRole('button', { name: '展开下一层' })).toHaveCount(0);
  await page.getByLabel('本次参考范围').selectOption('structural_relevance');
  const sent = page.waitForRequest(request => request.method() === 'POST' && request.url().endsWith('/actions'));
  await page.getByRole('button', { name: '阅读详细讲解' }).click();
  expect((await sent).postDataJSON().context_strategy).toBe('structural_relevance');
  await expect(page.getByRole('button', { name: '生成新的讲解' })).toBeVisible();
  await expect(page.getByLabel('内容版本')).toHaveValue('2');
  await page.getByLabel('补充要求或反馈（选填）').fill('这个固定示例存在内容疑点，请核对。');
  await page.getByLabel('反馈类型').selectOption('factual_error');
  await page.getByRole('button', { name: '只保存反馈' }).click();
  await expect(page.getByText('此版本已记录内容问题', { exact: false })).toBeVisible();
  await expect(page.getByRole('region', { name: '正文记录与缺口' }).getByText('这个固定示例存在内容疑点，请核对。')).toBeVisible();
  await page.getByLabel('补充要求或反馈（选填）').fill('还缺少空区间的边界例子。');
  await page.getByLabel('反馈类型').selectOption('omission');
  await page.getByRole('button', { name: '只保存反馈' }).click();
  await expect(page.getByRole('region', { name: '正文记录与缺口' }).getByText('报告遗漏', { exact: false })).toBeVisible();
  await page.getByLabel('内容版本').selectOption('1');
  await expect(page.getByText('已保存内容 · 版本 1')).toBeVisible();
  await expect(page.getByRole('region', { name: '正文记录与缺口' }).getByText('这个固定示例存在内容疑点，请核对。')).toHaveCount(0);
  await page.getByRole('button', { name: '修改设定' }).click();
  await expect(page.getByRole('dialog', { name: '修改学习方向' })).toBeVisible();
  await page.getByRole('dialog').getByLabel('主要用途').fill('希望继续练习边界条件。');
  await page.getByRole('dialog').getByLabel('学习主题').fill('协议与边界 · 修改后的主题');
  await page.getByRole('dialog').getByLabel('次要用途（每行一项）').fill('解释概念联系\n练习故障分析');
  await page.getByRole('button', { name: '保存新设定' }).click();
  await expect(page.getByText('判定待重评')).toBeVisible();
  await expect(page.getByRole('button', { name: '展开下一层' })).toHaveCount(0);
  await page.getByRole('button', { name: '重新评估展开判定' }).click();
  await expect(page.getByRole('button', { name: '展开下一层' })).toBeVisible();
  await page.getByRole('button', { name: '展开下一层' }).click();
  await expect(page.getByRole('button', { name: /知识节点.*基本例子/ })).toBeVisible();
  const current = page.getByLabel('内容版本');
  await current.selectOption({ index: 0 });
  const version = await current.inputValue();
  await page.getByRole('button', { name: '重新生成这一层' }).click();
  await expect(page.getByRole('heading', { name: '待确认的新结构' })).toBeVisible();
  await expect(current).toHaveValue(version);
  await page.getByRole('button', { name: '确认采用这个结构' }).click();
  await expect(page.getByRole('heading', { name: '待确认的新结构' })).toHaveCount(0);
  await expect(current).toHaveValue(String(Number(version) + 1));
  await page.reload();
  await expect(page.getByRole('region', { name: '正文记录与缺口' }).getByText('还缺少空区间的边界例子。')).toBeVisible();
  await expect(page.getByText('协议与边界 · 修改后的主题')).toBeVisible();
  await expect(page.getByText('解释概念联系')).toBeVisible();
  await expect(page.getByText('练习故障分析')).toBeVisible();
  await expect(page.getByRole('heading', { name: '应用与边界', exact: true }).first()).toBeVisible();
  await expect(page.getByRole('button', { name: /知识节点.*基本例子/ })).toBeVisible();
  expect(errors).toEqual([]);
  await page.screenshot({ path: '../.data/qa/m2-knowledge.png', fullPage: true });
});
