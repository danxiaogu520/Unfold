import { expect, test } from '@playwright/test';

test('questions hide answers, exact grading, disable and version history persist', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('你想学习什么？').fill('练习版本 · 浏览器验收');
  await page.getByLabel('你希望用它做什么？').fill('验证理解与历史作答。');
  await page.getByRole('button', { name: '开始探索' }).click();
  await expect(page.getByRole('checkbox', { name: '暂不确定', exact: true })).toBeVisible();
  await page.getByRole('checkbox', { name: '暂不确定', exact: true }).check();
  await page.getByRole('button', { name: '整理学习设定' }).click();
  await expect(page.getByRole('heading', { name: '下一层知识' })).toBeVisible();
  await expect(page.getByRole('heading', { name: '检验一下理解' })).toBeVisible();
  await page.getByRole('button', { name: '生成练习', exact: true }).click();
  await expect(page.locator('.practice-question')).toHaveCount(3);
  await expect(page.locator('.answer-result')).toHaveCount(0);
  const single = page.locator('.practice-question').nth(0);
  await single.getByRole('radio').nth(0).check();
  await single.getByRole('button', { name: '提交作答' }).click();
  await expect(single.getByText('本次答案符合已保存答案')).toBeVisible();
  const multiple = page.locator('.practice-question').nth(1);
  await multiple.getByRole('checkbox').nth(0).check();
  await multiple.getByRole('button', { name: '提交作答' }).click();
  await expect(multiple.getByText('本次答案与已保存答案不同')).toBeVisible();
  await expect(multiple.getByText(/需要例子或前置说明时/)).toBeVisible();
  await multiple.getByRole('checkbox').nth(2).check();
  await multiple.getByRole('button', { name: '提交作答' }).click();
  await expect(multiple.getByText('本次答案符合已保存答案')).toBeVisible();
  await multiple.getByRole('button', { name: '题目有问题' }).click();
  await page.getByLabel('题目问题说明').fill('示例需要更明确的语境。');
  await page.getByRole('button', { name: '报告问题并停用此题' }).click();
  await expect(multiple.getByText(/此题已报告问题并停用/)).toBeVisible();
  await expect(multiple.getByRole('button', { name: '提交作答' })).toBeDisabled();
  await page.getByRole('button', { name: '生成新版练习' }).click();
  await expect(page.getByLabel('练习版本', { exact: true })).toBeVisible();
  await expect(page.locator('.answer-result')).toHaveCount(0);
  const oldVersion = await page.getByLabel('练习版本', { exact: true }).locator('option').nth(1).getAttribute('value');
  await page.getByLabel('练习版本', { exact: true }).selectOption(oldVersion!);
  await expect(page.locator('.answer-result')).toHaveCount(2);
  await page.screenshot({ path: '../.data/qa/m4-practice.png', fullPage: true });
  let posts = 0;
  page.on('request', request => { if (request.method() === 'POST') posts++; });
  await page.reload();
  await expect(page.getByLabel('练习版本', { exact: true })).toBeVisible();
  expect(posts).toBe(0);
});
