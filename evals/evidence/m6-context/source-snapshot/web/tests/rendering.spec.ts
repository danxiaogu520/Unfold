import { expect, test } from '@playwright/test';

test('formula, highlighted code, diagram fallback and saved source image render safely', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByLabel('你想学习什么？').fill('二分查找 · M4 渲染验收');
  await page.getByLabel('你希望用它做什么？').fill('理解区间缩小与中点公式。');
  await page.getByRole('button', { name: '开始探索' }).click();
  await page.getByRole('checkbox', { name: '暂不确定', exact: true }).check();
  await page.getByRole('button', { name: '整理学习设定' }).click();
  await page.getByRole('button', { name: '生成第一层大纲 →' }).click();
  await page.getByLabel('补充要求或反馈（选填）').fill('M4 渲染验收');
  await page.getByRole('button', { name: '阅读详细讲解' }).click();
  await expect(page.locator('.katex')).toBeVisible();
  await expect(page.locator('code.hljs')).toBeVisible();
  await expect(page.frameLocator('iframe[title="二分查找流程"]').locator('svg')).toBeVisible();
  const diagram = page.frameLocator('iframe[title="二分查找流程"]');
  await expect(diagram.getByText('检查区间', { exact: true })).toBeVisible();
  await expect(diagram.getByText('比较中点', { exact: true })).toBeVisible();
  await expect(diagram.getByText('缩小区间', { exact: true })).toBeVisible();
  await page.locator('iframe[title="二分查找流程"]').screenshot({ path: '../.data/qa/m4-diagram.png' });
  await expect(page.getByText('错误图示的文字仍然可读。')).toBeVisible();
  await expect(page.getByText('越界图示保留文字替代。')).toBeVisible();
  await expect(page.getByText('图片已保存', { exact: true })).toBeVisible();
  const image = page.getByRole('img', { name: '二分查找示意图' });
  await expect(image).toBeVisible();
  expect(await image.evaluate((node: HTMLImageElement) => node.complete && node.naturalWidth === 960)).toBe(true);
  await expect(page.getByText(/Kurt Kaiser/)).toBeVisible();
  await expect(page.getByRole('link', { name: 'CC0', exact: true })).toBeVisible();
  expect(await page.evaluate(() => (window as unknown as { unfoldInjected?: boolean }).unfoldInjected)).toBeUndefined();
  const unsafe = page.getByRole('link', { name: '不安全链接' });
  expect(await unsafe.getAttribute('href')).not.toContain('javascript:');
  expect(await page.locator('iframe[title="二分查找流程"]').getAttribute('sandbox')).toBe('');
  expect(errors).toEqual([]);
  await page.screenshot({ path: '../.data/qa/m4-rendering.png', fullPage: true });
  let posts = 0;
  page.on('request', request => { if (request.method() === 'POST') posts++; });
  await page.reload();
  await expect(page.getByRole('img', { name: '二分查找示意图' })).toBeVisible();
  expect(posts).toBe(0);
});
